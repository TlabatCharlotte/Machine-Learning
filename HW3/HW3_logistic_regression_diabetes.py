plt.plot(range(1, iterations + 1), acc_history_validation, color='orange', label='test accuracy')
plt.xlabel('Number of iterations')
plt.ylabel('Accuracy')
plt.title('Accuracy Over Iterations')
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.show()